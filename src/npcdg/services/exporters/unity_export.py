"""Unity exporter — emits a ScriptableObject-shaped JSON and a C# stub."""

from __future__ import annotations

from pathlib import Path

from npcdg.models.dialogue import DialoguePack


_CS_TEMPLATE = """// Auto-generated by npc-dialogue-generator {version} — do not hand-edit.
using System;
using System.Collections.Generic;
using UnityEngine;

[CreateAssetMenu(fileName = "{pack}", menuName = "NPC Dialogue/{pack}")]
public class {pack}Dialogue : ScriptableObject
{{
    [Serializable]
    public class Node
    {{
        public string nodeId;
        public string speaker;
        public string text;
        public List<string> next = new List<string>();
    }}

    public List<Node> nodes = new List<Node>();
    public string rootId = "{root}";
}}
"""


def export_unity(pack: DialoguePack, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for tree in pack.trees.values():
        (out_dir / f"{tree.name}.json").write_text(tree.model_dump_json(indent=2), encoding="utf-8")
    class_name = "".join(ch for ch in pack.name if ch.isalnum()) or "Pack"
    cs = _CS_TEMPLATE.format(version="0.9.3", pack=class_name, root=next(iter(pack.trees.values())).root if pack.trees else "")
    (out_dir / f"{class_name}Dialogue.cs").write_text(cs, encoding="utf-8")